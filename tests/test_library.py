"""library.py: what a project's library holds, in a plain project and in a vault that uses Texere.

No real Texere bibliography was available when this was written. The index below is built from the lab plan's
description of one: a JSON list whose entries have `id`, `obsidianPath` and `reading-status`. The optional
`title`, `issued` and `DOI` fields are an assumption about what else such an entry may carry; the reader must
work without them.
"""
import contextlib
import io
import json
import sys
import tempfile
import unittest
from pathlib import Path

from helpers import ROOT

import library  # noqa: E402

INDEX = [
    {"id": "hiltunen2008future", "obsidianPath": "1. References/hiltunen2008future.md", "reading-status": "read",
     "title": "The future sign and its three dimensions", "issued": {"date-parts": [[2008]]}, "DOI": "10.1016/j.futures.2007.08.021"},
    {"id": "sharpe2016three", "obsidianPath": "1. References/sharpe2016three.md", "reading-status": "unread"},
    {"obsidianPath": "1. References/no-key.md"},
    "not an entry",
]


def run(argv: list[str]) -> tuple[int, str]:
    out = io.StringIO()
    saved = sys.argv
    sys.argv = ["library.py", *argv]
    try:
        with contextlib.redirect_stdout(out):
            code = library.main()
    finally:
        sys.argv = saved
    return code, out.getvalue()


class Library(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name).resolve() / "vault"
        notes = self.root / "research" / "notes" / "methods"
        notes.mkdir(parents=True)
        (notes / "walters-2023-fabricated-citations.md").write_text(
            "# Fabrication and errors in the bibliographic citations generated by ChatGPT (Walters & Wilder, 2023)\n\n"
            "- **Source:** Scientific Reports 13: 14045 · https://doi.org/10.1038/s41598-023-41032-5\n- **Read:** full text · 2026-11-21\n", encoding="utf-8")
        (notes / "small-1973-co-citation.md").write_text(
            "# Co-citation in the scientific literature (Small, 1973)\n\n- **Source:** JASIS · https://doi.org/10.1002/asi.4630240406\n"
            "- **Evidence:** analytical · **abstract only**.\n", encoding="utf-8")
        (self.root / "research" / "signals").mkdir()
        (self.root / "research" / "signals" / "2026-11-21-a-signal.md").write_text("# A signal\n- **Id:** SG-001\n", encoding="utf-8")

    def tearDown(self):
        self._tmp.cleanup()

    def texere(self, data=INDEX) -> Path:
        folder = self.root / "Support" / "Texere" / "Bibliography"
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "bibliography.json").write_text(json.dumps(data), encoding="utf-8")
        return folder / "bibliography.json"

    def snapshot(self) -> dict:
        return {str(f.relative_to(self.root)): f.read_bytes() for f in self.root.rglob("*") if f.is_file()}

    def test_a_plain_project_lists_its_notes_with_how_much_was_read(self):
        code, out = run([str(self.root)])
        self.assertEqual(code, 0)
        self.assertIn("Library of vault: 2 source notes, 1 signal notes.", out)
        self.assertIn("- walters-2023-fabricated-citations · Walters & Wilder 2023 · 10.1038/s41598-023-41032-5 · read: full text · research/notes/methods/walters-2023-fabricated-citations.md", out)
        self.assertIn("- small-1973-co-citation · Small 1973 · 10.1002/asi.4630240406 · read: abstract only · ", out)
        self.assertNotIn("Texere", out)

    def test_a_texere_vault_also_lists_its_bibliography_and_says_how_to_cite_it(self):
        self.texere()
        code, out = run([str(self.root)])
        self.assertIn("Texere bibliography (Support/Texere/Bibliography/bibliography.json): 2 entries. Cite one as [@key, p. N].", out)
        self.assertIn("- @hiltunen2008future · reading-status: read · 1. References/hiltunen2008future.md · The future sign and its three dimensions · 2008 · 10.1016/j.futures.2007.08.021", out)
        self.assertIn("- @sharpe2016three · reading-status: unread · 1. References/sharpe2016three.md", out)

    def test_the_vault_is_found_from_a_folder_inside_it(self):
        self.texere()
        code, out = run([str(self.root / "research")])
        self.assertIn("2 entries", out)

    def test_reading_never_changes_a_file(self):
        self.texere()
        before = self.snapshot()
        run([str(self.root)])
        run([str(self.root), "--has", "hiltunen2008future"])
        run([str(self.root), "--json"])
        self.assertEqual(self.snapshot(), before)

    def test_has_answers_by_doi_key_or_title_words(self):
        self.texere()
        code, out = run([str(self.root), "--has", "https://doi.org/10.1038/S41598-023-41032-5", "--has", "@sharpe2016three", "--has", "the future sign and its three dimensions",
                         "--has", "co-citation in the scientific literature"])
        self.assertEqual(code, 0)
        self.assertIn("note research/notes/methods/walters-2023-fabricated-citations.md (read: full text)", out)
        self.assertIn("Texere @sharpe2016three (reading-status: unread), cite as [@sharpe2016three, p. N]", out)
        self.assertIn("Texere @hiltunen2008future (reading-status: read)", out)
        self.assertIn("note research/notes/methods/small-1973-co-citation.md (read: abstract only)", out)

    def test_has_says_when_the_library_does_not_hold_a_work(self):
        code, out = run([str(self.root), "--has", "10.9999/not-here"])
        self.assertEqual(code, 1)
        self.assertEqual(out.strip(), "10.9999/not-here: not in the library")

    def test_a_bibliography_that_cannot_be_read_is_reported_not_raised(self):
        self.texere()
        (self.root / "Support" / "Texere" / "Bibliography" / "bibliography.json").write_text("{not json", encoding="utf-8")
        code, out = run([str(self.root)])
        self.assertEqual(code, 0)
        self.assertIn("could not be read", out)
        self.texere({"entries": []})
        code, out = run([str(self.root)])
        self.assertIn("is not a list of entries", out)

    def test_json_carries_the_same_facts(self):
        self.texere()
        code, out = run([str(self.root), "--json"])
        data = json.loads(out)
        self.assertEqual([n["name"] for n in data["notes"]], ["small-1973-co-citation", "walters-2023-fabricated-citations"])
        self.assertEqual(data["other"], {"signals": 1})
        self.assertEqual([e["key"] for e in data["texere"]["entries"]], ["hiltunen2008future", "sharpe2016three"])
        self.assertEqual(data["texere"]["entries"][1]["status"], "unread")

    def test_a_folder_with_no_library_says_so(self):
        with tempfile.TemporaryDirectory() as empty:
            code, out = run([empty])
        self.assertEqual(code, 0)
        self.assertIn("No library in", out)

    def test_this_repository_s_own_library_is_listed(self):
        code, out = run([str(ROOT)])
        self.assertIn("walters-2023-fabricated-citations", out)
        self.assertIn("read: abstract only", out)


if __name__ == "__main__":
    unittest.main()
