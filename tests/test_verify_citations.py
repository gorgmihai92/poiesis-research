import verify_quotes as vq  # noqa: E402

WALTERS = "10.1038/s41598-023-41032-5"
WALTERS_TITLE = "Fabrication and errors in the bibliographic citations generated by ChatGPT"


def doi_of(text: str) -> str | None:
    m = vc.DOI.search(text)
    return vc.trim(m.group(1)) if m else None


class ReadingADoi(unittest.TestCase):
    def test_a_bare_doi_is_read(self):
        """Found by the audit of 2026-11-23: the template asks for the DOI itself, and a bare one was NO DOI."""
        self.assertEqual(doi_of(f"- **Source:** Scientific Reports 13: 14045 · {WALTERS}\n"), WALTERS)
        self.assertEqual(doi_of(f"| Walters & Wilder, 2023 | {WALTERS} | by DOI in Crossref |\n"), WALTERS)
        self.assertEqual(doi_of(f"{WALTERS} is the DOI.\n"), WALTERS)
        self.assertEqual(doi_of(f"# T\n{WALTERS}\n"), WALTERS)
        self.assertEqual(doi_of(f"Scientific Reports ({WALTERS})."), WALTERS)
        self.assertEqual(doi_of(f"- **DOI:** {WALTERS}\n"), WALTERS)

    def test_trailing_punctuation_is_trimmed_and_inner_parentheses_kept(self):
        self.assertEqual(doi_of(f"See {WALTERS}."), WALTERS)
        self.assertEqual(doi_of(f"See {WALTERS}, and more"), WALTERS)
        self.assertEqual(doi_of("Futures 30 (10.1016/S0016-3287(98)00086-X)."), "10.1016/S0016-3287(98)00086-X")

    def test_closing_marks_after_a_doi_are_dropped(self):
        """Found by the review of 2.6.1: bold, italic, closing quotation marks, a `·` or a colon were kept."""
        for text in (f"**{WALTERS}**", f"“{WALTERS}”", f"_{WALTERS}_", f"Source — {WALTERS}·", f"DOI {WALTERS}: Scientific Reports",
                     f"‘{WALTERS}’", f"*{WALTERS}*."):
            self.assertEqual(doi_of(text), WALTERS, text)

    def test_balanced_parentheses_are_kept_inside_parentheses(self):
        """Found by the review of 2.6.1: verify_quotes.py and library.py cut this one at its inner parenthesis."""
        self.assertEqual(doi_of("Business Horizons (10.1016/0007-6813(90)90040-i)."), "10.1016/0007-6813(90)90040-i")

    def test_a_publisher_s_doi_address_and_arxiv_are_read(self):
        self.assertEqual(doi_of("https://dl.acm.org/doi/10.1145/3544548.3581000"), "10.1145/3544548.3581000")
        self.assertEqual(doi_of("https://onlinelibrary.wiley.com/doi/full/10.1002/abc.123."), "10.1002/abc.123")
        self.assertEqual(doi_of("arXiv:10.48550/arXiv.2310.06825"), "10.48550/arXiv.2310.06825")

    def test_a_prefixed_doi_is_still_read(self):
        self.assertEqual(doi_of(f"· https://doi.org/{WALTERS} (pages = PDF pages)"), WALTERS)
        self.assertEqual(doi_of("- **Source:** doi: 10.1136/ebmed-2016-110401\n"), "10.1136/ebmed-2016-110401")
        self.assertEqual(doi_of(f"DOI:{WALTERS}"), WALTERS)

    def test_an_address_with_a_doi_is_read_once(self):
        self.assertEqual([vc.trim(d) for d in vc.DOI.findall(f"https://doi.org/{WALTERS}")], [WALTERS])

    def test_a_doi_like_path_in_another_address_is_not_read_as_a_doi(self):
        self.assertIsNone(doi_of(f"https://www.nature.com/articles/{WALTERS}"))
        self.assertIsNone(doi_of("a version number 110.12345/x and a placeholder <10.xxxx/…>"))


class OneRuleInThreeScripts(unittest.TestCase):
    """verify_citations.py, verify_quotes.py and library.py each keep a copy of the DOI pattern and of trim: they
    must read the same DOI from the same text."""

    CASES = [f"**{WALTERS}**", f"“{WALTERS}”", f"_{WALTERS}_", f"DOI {WALTERS}: Scientific Reports", f"Source — {WALTERS}·",
             "(10.1016/0007-6813(90)90040-i).", "(10.1016/S0016-3287(98)00086-X).", "https://dl.acm.org/doi/10.1145/3544548.3581000",
             "arXiv:10.48550/arXiv.2310.06825", f"| A | {WALTERS} |", f"https://doi.org/{WALTERS}.", f"https://www.nature.com/articles/{WALTERS}",
             "[10.1038/abc](https://doi.org/10.1038/abc)", "10.1111/aaa,10.2222/bbb"]

    def test_the_same_dois_are_read(self):
        for text in self.CASES:
            read = [sorted({m.trim(d) for d in m.DOI.findall(text)}) for m in (vc, vq, library)]
            self.assertEqual(read[0], read[1], text)
            self.assertEqual(read[0], read[2], text)

    def test_the_same_note_doi_is_read(self):
        note = f"# T (A, 2020)\n\n- **Source:** Journal 1(2): 3–4 ·\n  https://doi.org/{WALTERS}.\n\n## Later work\n- A critique · 10.1234/critique-2020\n"
        self.assertEqual({vc.note_doi(note), vq.note_doi(note), library.note_doi(note)}, {WALTERS})


class Notes(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.notes = Path(self._tmp.name) / "notes"
        self.notes.mkdir()
        self.asked: list[str] = []
        self.titles = {WALTERS: WALTERS_TITLE}
        self._saved = (vc.registered_title, vc.urllib.request.urlopen)
        vc.registered_title = self.registry
        vc.urllib.request.urlopen = self.no_network

    def tearDown(self):
        vc.registered_title, vc.urllib.request.urlopen = self._saved
        self._tmp.cleanup()

    def registry(self, doi: str) -> str | None:
        self.asked.append(doi)
        if self.titles is None:  # the registry cannot be reached
            raise OSError("could not reach doi.org")
        return self.titles.get(doi)

    @staticmethod
    def no_network(*args, **kwargs):
        raise AssertionError("the test did not expect a request")

    def note(self, name: str, body: str) -> None:
        (self.notes / f"{name}.md").write_text(body, encoding="utf-8")

    def run_it(self) -> tuple[int, str]:
        out = io.StringIO()
        saved = sys.argv
        sys.argv = ["verify_citations.py", str(self.notes)]
        try:
            with contextlib.redirect_stdout(out):
                code = vc.main()
        finally:
            sys.argv = saved
        return code, out.getvalue()

    def test_a_note_with_a_bare_doi_is_checked(self):
        self.note("walters-2023", f"# {WALTERS_TITLE} (Walters & Wilder, 2023)\n\n- **Source:** Scientific Reports 13: 14045 · {WALTERS}\n")
        code, out = self.run_it()
        self.assertEqual(code, 0, out)
        self.assertEqual(self.asked, [WALTERS])
        self.assertIn(f"OK        walters-2023.md · {WALTERS} · registered: {WALTERS_TITLE}", out)

    def test_a_note_with_no_doi_does_not_fail(self):
        """A book or a page may have no DOI: NO DOI alone keeps the exit code 0."""
        self.note("a-book-1998", "# A book (Someone, 1998)\n\n- **Source:** A Press · https://example.org/a-book\n")
        code, out = self.run_it()
        self.assertEqual(code, 0, out)
        self.assertIn("NO DOI    a-book-1998.md", out)
        self.assertEqual(self.asked, [])

    def test_a_doi_inside_another_address_is_unread_and_fails(self):
        self.note("walters-2023", f"# {WALTERS_TITLE} (Walters & Wilder, 2023)\n\n- **Source:** https://www.nature.com/articles/{WALTERS}\n")
        code, out = self.run_it()
        self.assertEqual(code, 1, out)
        self.assertIn(f"UNREAD    walters-2023.md · {WALTERS} stands inside other text on the Source line: write the DOI itself there", out)
        self.assertEqual(self.asked, [])

    def test_only_the_source_line_gives_the_note_s_doi(self):
        """Found by the review of 2.6.1: a book with no DOI was checked against the DOI of a critique under Later work."""
        self.note("a-book-1998", "# A book about things (Someone, 1998)\n\n- **Source:** A Press · https://example.org/a-book\n\n"
                                 "## Later work\n- A critique that cites it · 10.1234/critique-2020 (checked 2026-11-23)\n"
                                 f"- Read about at https://www.nature.com/articles/{WALTERS}\n")
        code, out = self.run_it()
        self.assertEqual(code, 0, out)
        self.assertIn("NO DOI    a-book-1998.md", out)
        self.assertEqual(self.asked, [])

    def test_a_publisher_s_doi_address_on_the_source_line_is_checked(self):
        self.titles = {"10.1145/3544548.3581000": "A paper"}
        self.note("a-paper-2023", "# A paper (Someone, 2023)\n\n- **Source:** CHI 2023 · https://dl.acm.org/doi/10.1145/3544548.3581000\n")
        code, out = self.run_it()
        self.assertEqual(code, 0, out)
        self.assertEqual(self.asked, ["10.1145/3544548.3581000"])

    def test_a_doi_in_bold_on_the_source_line_is_checked(self):
        self.note("walters-2023", f"# {WALTERS_TITLE} (Walters & Wilder, 2023)\n\n- **Source:** Scientific Reports · **{WALTERS}**\n")
        code, out = self.run_it()
        self.assertEqual(code, 0, out)
        self.assertEqual(self.asked, [WALTERS])

    def test_a_check_that_could_not_be_completed_fails_and_says_so(self):
        """Found by the audit of 2026-11-23: with doi.org out of reach, every note passed."""
        self.note("walters-2023", f"# {WALTERS_TITLE} (Walters & Wilder, 2023)\n\n- **Source:** {WALTERS}\n")
        self.titles = None
        code, out = self.run_it()
        self.assertEqual(code, 1, out)
        self.assertIn(f"ERROR     walters-2023.md · {WALTERS}: could not reach doi.org", out)
        self.assertIn("The check could not be completed: 1 note could not be looked up in the registry. They have not passed", out)

    def test_not_found_and_mismatch_still_fail(self):
        self.note("gone-2020", "# Gone (Someone, 2020)\n\n- **Source:** 10.1234/not-registered\n")
        code, out = self.run_it()
        self.assertEqual(code, 1, out)
        self.assertIn("NOT FOUND gone-2020.md · 10.1234/not-registered", out)
        (self.notes / "gone-2020.md").unlink()
        self.note("wrong-2023", f"# A different title altogether (Someone, 2023)\n\n- **Source:** {WALTERS}\n")
        code, out = self.run_it()
        self.assertEqual(code, 1, out)
        self.assertIn("MISMATCH  wrong-2023.md", out)


if __name__ == "__main__":
    unittest.main()
